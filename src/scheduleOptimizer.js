import { coverageForDay } from './scheduleCoverage.js';
import { assertSchedulePublicationSize } from './schedulePublicationLimits.js';
import { isWorking, scheduleRuleIssues, shiftDate } from './scheduleDayRules.js';
import { findScheduleAbsence, isFullDayAbsence } from './scheduleAbsences.js';

const operational = ['status', 'shiftStart', 'shiftEnd', 'breakStart', 'breakEnd', 'breakMinutes', 'extraHours', 'shift'];
const inRange = (row, date) => (row.startDate || row.date) <= date && (row.endDate || row.date || row.startDate) >= date;
const keyOf = row => `${String(row.userId)}|${row.date}`;
const time = value => /^([01]\d|2[0-3]):[0-5]\d$/.test(value || '') ? Number(value.slice(0, 2)) * 60 + Number(value.slice(3)) : NaN;
const clock = value => `${String(Math.floor(value / 60) % 24).padStart(2, '0')}:${String(value % 60).padStart(2, '0')}`;
export const isReplaceableSchedule = row => row.autoGenerated === true && !row.manuallyAdjusted && !row.locked && ['Presencial', 'Home Office', 'Folga', 'Feriado'].includes(row.status);
export const isProtectedProposalRow = row => Boolean(row.preservedExisting || row.preservedAbsence);
export const isFixedProposalRow = row => Boolean(isProtectedProposalRow(row) || row.locked || row.manuallyAdjusted || row.pinned || row.constraintLocked || row.ruleApplied);

export function scheduleSignature(rows) {
  const stable = value => Array.isArray(value) ? value.map(stable) : value && typeof value === 'object'
    ? Object.fromEntries(Object.keys(value).sort().filter(key => value[key] !== undefined).map(key => [key, stable(value[key])])) : value;
  return JSON.stringify(rows.slice().sort((a, b) => String(a.id).localeCompare(String(b.id))).map(stable));
}

export function prepareScheduleProposal(rows, { history = [], absences = [], rules = {}, draftPins = [] } = {}) {
  const pins = new Map(draftPins.filter(row => row.locked || row.manuallyAdjusted).map(row => [keyOf(row), row]));
  return rows.map(source => {
    const row = { ...source, userId: String(source.userId), restEveryDays: Number(source.restEveryDays) || Number(rules.restEveryDays) || 7, workDaysPerWeek: Number(source.workDaysPerWeek) || Number(rules.workDaysPerWeek) || 5 };
    const saved = history.filter(item => String(item.userId) === row.userId && inRange(item, row.date) && !isReplaceableSchedule(item));
    if (saved.length) {
      const item = saved.find(item => !isWorking(item)) || saved[0];
      return { ...row, ...Object.fromEntries(operational.map(field => [field, item[field] ?? (field === 'extraHours' || field === 'breakMinutes' ? 0 : '')])),
        shiftEnd: item.baseShiftEnd || item.shiftEnd || '', extraHours: item.baseShiftEnd ? Number(item.extraHours) || 0 : 0,
        locked: true, preservedExisting: true, sourceScheduleId: item.id, ruleConflicts: saved.length > 1 ? ['Marcações existentes sobrepostas; revise o calendário'] : [],
        ruleReason: 'Marcação já publicada preservada', manuallyAdjusted: Boolean(item.manuallyAdjusted) };
    }
    const sameDayAbsence = absences.find(item => String(item.userId) === row.userId && inRange(item, row.date));
    const absence = findScheduleAbsence(absences, row.userId, row.date, row.shiftStart, row.shiftEnd) || sameDayAbsence;
    if (absence) {
      const fullDay = isFullDayAbsence(absence, row.date);
      if (fullDay) return { ...row, status: /f[eé]rias/i.test(absence.reason || '') ? 'Férias' : 'Ausência', shiftStart: '', shiftEnd: '', breakStart: '', breakEnd: '', breakMinutes: 0, extraHours: 0, locked: true, preservedAbsence: true, ruleReason: 'Ausência registrada preservada' };
      row.constraintLocked = true;
      row.ruleReason = 'Dia com ausência parcial preservado';
    }
    const pin = pins.get(keyOf(row));
    if (pin && !absence) Object.assign(row, Object.fromEntries(operational.map(field => [field, pin[field] ?? row[field]])), { locked: true, manuallyAdjusted: true, ruleReason: 'Dia fixado manualmente' });
    const weekday = new Date(`${row.date}T12:00:00`).getDay();
    if (weekday === 6 && rules.employeeOverrides?.[row.userId]?.saturdayEnd) row.pinned = true;
    return row;
  });
}

export function balancePreparedScheduleProposal(prepared, baseline, requirements, context = {}) {
  const rows = prepared.map(row => ({ ...row }));
  const groups = new Map();
  rows.forEach((row, index) => { const key = row.userId + '|' + row.weekKey; groups.set(key, [...(groups.get(key) || []), index]); });
  for (const indexes of groups.values()) {
    const first = rows[indexes[0]];
    const source = baseline.filter(row => String(row.userId) === String(first.userId) && row.weekKey === first.weekKey);
    const absentWork = indexes.filter(index => rows[index].preservedAbsence && source.some(row => row.date === rows[index].date && isWorking(row))).length;
    const target = Math.max(0, source.filter(isWorking).length - absentWork);
    const daytime = row => isWorking(row) && time(row.shiftEnd) > time(row.shiftStart) && time(row.shiftEnd) + Number(row.extraHours || 0) * 60 < 1440;
    const template = source.find(row => daytime(row) && !row.pinned && !row.ruleApplied) || source.find(daytime);
    for (let pass = 0; pass < 7; pass++) {
      const count = indexes.filter(index => isWorking(rows[index])).length;
      if (count === target) break;
      const remove = count > target;
      let best = null;
      for (const index of indexes) {
        const row = rows[index];
        if (isFixedProposalRow(row) || (row.holiday && !row.holidayWorkingDay) || row.allowed === false || (remove ? !isWorking(row) : row.status !== 'Folga' || !template)) continue;
        const replacement = remove
          ? { ...row, status: 'Folga', shiftStart: '', shiftEnd: '', breakStart: '', breakEnd: '', breakMinutes: 0, extraHours: 0, shift: 'Folga', ruleReason: 'Folga compensada para preservar um dia fixo' }
          : { ...row, ...Object.fromEntries(operational.map(field => [field, template[field] ?? ''])), extraHours: 0, ruleReason: 'Trabalho redistribuído para preservar um dia fixo' };
        rows[index] = replacement;
        const issues = scheduleRuleIssues(rows.filter(item => String(item.userId) === String(row.userId)), context.history || []).filter(issue => issue.blocking);
        const score = issues.length ? Infinity : analyzeProposalCoverage(rows, requirements, context).missingMinutes;
        rows[index] = row;
        if (Number.isFinite(score) && (!best || score < best.score)) best = { index, replacement, score };
      }
      if (!best) break;
      rows[best.index] = best.replacement;
    }
  }
  return rows;
}

function retainedScheduleRecords(rows, history) {
  if (!rows.length) return history;
  const users = new Set(rows.map(row => String(row.userId)));
  const dates = rows.map(row => row.date).sort(), start = dates[0], end = dates.at(-1);
  const retained = [];
  for (const item of history) {
    if (!users.has(String(item.userId)) || !isReplaceableSchedule(item) || item.endDate < start || item.startDate > end) { retained.push(item); continue; }
    if (item.startDate < start) retained.push({ ...item, endDate: shiftDate(start, -1) });
    if (item.endDate > end) retained.push({ ...item, startDate: shiftDate(end, 1) });
  }
  return retained;
}

const proposalRecord = row => {
  const end = time(row.shiftEnd) + Math.round((Number(row.extraHours) || 0) * 60);
  return { ...row, id: `preview-${row.key}`, startDate: row.date, endDate: row.date, shiftEnd: isWorking(row) && Number.isFinite(end) ? clock(end) : row.shiftEnd };
};

export function proposalScheduleRecords(rows, history = []) {
  return [...retainedScheduleRecords(rows, history), ...rows.filter(row => !isProtectedProposalRow(row)).map(proposalRecord)];
}

// Keep stable calendar records indexed while evaluating only changed civil days.
// The previous day remains present so overnight shifts and absences still count.
function proposalCoverageEvaluator(rows, requirements, { history = [], absences = [], employees = [], getDepartments } = {}) {
  const retained = retainedScheduleRecords(rows, history);
  const byDate = new Map();
  rows.forEach((row, index) => byDate.set(row.date, [...(byDate.get(row.date) || []), index]));
  const stableByDate = new Map();
  return date => {
    const yesterday = shiftDate(date, -1);
    if (!stableByDate.has(date)) stableByDate.set(date, retained.filter(row => inRange(row, date) || inRange(row, yesterday)));
    const changing = [...(byDate.get(date) || []), ...(byDate.get(yesterday) || [])].map(index => rows[index]).filter(row => !isProtectedProposalRow(row)).map(proposalRecord);
    return { date, ...coverageForDay(date, requirements, { schedules: [...stableByDate.get(date), ...changing], absences, employees, getDepartments }) };
  };
}

const dayMetrics = day => {
  let required = 0, missing = 0, severity = 0, spare = 0, excess = 0;
  for (const rule of day.rules) for (const segment of rule.segments) {
    const duration = time(segment.end) - time(segment.start);
    required += duration * rule.minimum;
    missing += duration * segment.missing;
    // At equal total shortage, avoid concentrating the deficit on a few days.
    severity += duration * segment.missing ** 2 / rule.minimum;
    excess += duration * (segment.excess || 0);
    spare += duration * Math.max(0, segment.available - (rule.maximum ?? rule.minimum));
  }
  return { required, missing, severity, spare, excess };
};

export function analyzeProposalCoverage(rows, requirements, context = {}, selectedDates = null) {
  const evaluate = proposalCoverageEvaluator(rows, requirements, context);
  const days = [...new Set(rows.map(row => row.date))].filter(date => !selectedDates || selectedDates.has(date)).sort().map(evaluate);
  let requiredMinutes = 0, missingMinutes = 0, excessMinutes = 0, gaps = 0, unknown = 0;
  for (const day of days) {
    const metrics = dayMetrics(day);
    requiredMinutes += metrics.required;
    missingMinutes += metrics.missing;
    excessMinutes += metrics.excess;
    for (const rule of day.rules) { unknown += rule.unknown; gaps += rule.segments.filter(segment => segment.missing > 0).length; }
  }
  return { days, requiredMinutes, missingMinutes, excessMinutes, gaps, unknown, coveredPercent: requiredMinutes ? Math.round(1000 * (1 - missingMinutes / requiredMinutes)) / 10 : null };
}

export function buildCoverageFirstProposal(input, requirements, context = {}, options = {}) {
  return optimizeScheduleCoverage(input, requirements, context, options);
}

// One actionable entry per requirement/day, showing its worst uncovered slot.
export function coverageShortfalls(analysis, rows = []) {
  return analysis.days.flatMap(day => day.rules.flatMap(rule => {
    const worst = rule.segments.filter(segment => segment.missing > 0).sort((a, b) => b.missing - a.missing || a.start.localeCompare(b.start))[0];
    if (!worst) return [];
    const off = rows.filter(row => row.date === day.date && row.dept === rule.department && row.status === 'Folga');
    return [{ ...worst, date: day.date, department: rule.department, ruleId: rule.id, minimum: rule.minimum,
      adjustableRest: off.filter(row => !isFixedProposalRow(row) && (!row.holiday || row.holidayWorkingDay) && row.allowed !== false).length,
      fixedRest: off.filter(row => isFixedProposalRow(row) || (row.holiday && !row.holidayWorkingDay) || row.allowed === false).length }];
  })).sort((a, b) => b.missing / b.minimum - a.missing / a.minimum || b.missing - a.missing || a.date.localeCompare(b.date) || a.start.localeCompare(b.start));
}

// Repair the largest coverage deficits first, moving an existing workday to a
// free day of the same person/week. Never increase days, hours or rule conflicts.
export function optimizeScheduleCoverage(input, requirements, context = {}, options = {}) {
  const rows = input.map(row => ({ ...row }));
  const before = analyzeProposalCoverage(rows, requirements, context);
  let evaluations = 0, swaps = 0, limited = false;
  if (!before.requiredMinutes || !before.missingMinutes) return { rows, before, after: before, swaps, evaluations, limited };
  const history = context.history || [];
  const groups = new Map(), people = new Map(), weeks = new Map();
  rows.forEach((row, index) => {
    const key = `${row.userId}|${row.weekKey}`;
    groups.set(key, [...(groups.get(key) || []), index]);
    people.set(String(row.userId), [...(people.get(String(row.userId)) || []), index]);
    weeks.set(row.weekKey, [...(weeks.get(row.weekKey) || []), index]);
  });
  const maxEvaluations = options.maxEvaluations ?? Math.min(24000, Math.max(1600, groups.size * 40));
  const maxSwaps = options.maxSwaps ?? Math.max(100, groups.size * 5);
  const weekday = date => new Date(`${date}T12:00:00`).getDay();
  const operationalNeed = row => requirements.some(rule => rule.department === row.dept && rule.weekdays?.includes(weekday(row.date)) && Number(rule.minimum) > 0);
  // A necessidade da operação pode ativar um dia fora do padrão genérico. Regras
  // individuais, ausências, feriados protegidos e dias fixados continuam imutáveis.
  const isFlexible = row => !isFixedProposalRow(row) && (!row.holiday || row.holidayWorkingDay) && (row.allowed !== false || operationalNeed(row)) && ['Presencial', 'Home Office', 'Folga'].includes(row.status);
  const safeDaytime = row => Number.isFinite(time(row.shiftStart)) && time(row.shiftEnd) > time(row.shiftStart) && time(row.shiftEnd) + (Number(row.extraHours) || 0) * 60 < 1440;
  const evaluate = proposalCoverageEvaluator(rows, requirements, context);
  const days = new Map(before.days.map(day => [day.date, day]));
  const personIssues = userId => scheduleRuleIssues(people.get(String(userId)).map(index => rows[index]), history).filter(issue => issue.blocking);
  const issueKey = issue => `${issue.key}|${issue.message}`;
  const baselineIssues = new Map([...people.keys()].map(userId => [userId, new Set(personIssues(userId).map(issueKey))]));
  // Each week gets a share of the budget. Earlier weeks cannot exhaust the month.
  // Start from the end: following-week rest days are known before moving a weekend.
  let weekIndex = 0;
  for (const [, indexes] of [...weeks.entries()].sort(([a], [b]) => String(b).localeCompare(String(a)))) {
    const budget = Math.floor(maxEvaluations / weeks.size) + (weekIndex++ < maxEvaluations % weeks.size ? 1 : 0);
    const deadline = evaluations + budget;
    const dates = [...new Set(indexes.map(index => rows[index].date))];
    let changed = true;
    while (changed && evaluations < deadline && swaps < maxSwaps) {
      changed = false;
      const targets = dates.filter(date => dayMetrics(days.get(date)).missing > 0).sort((a, b) => {
        const worst = date => Math.max(0, ...days.get(date).rules.flatMap(rule => rule.segments.map(segment => segment.missing / rule.minimum)));
        return worst(b) - worst(a) || dayMetrics(days.get(b)).missing - dayMetrics(days.get(a)).missing || a.localeCompare(b);
      });
      for (const targetDate of targets) {
        let applied = false;
        const target = days.get(targetDate);
        const departments = new Set(target.rules.filter(rule => rule.segments.some(segment => segment.missing > 0)).map(rule => rule.department));
        const candidates = indexes.filter(index => {
          const row = rows[index];
          const employee = context.employees?.find(user => String(user.id) === String(row.userId));
          const department = row.dept || (employee && context.getDepartments ? context.getDepartments(employee)[0] : '');
          return row.date === targetDate && row.status === 'Folga' && isFlexible(row) && departments.has(department);
        }).flatMap(offIndex => (groups.get(`${rows[offIndex].userId}|${rows[offIndex].weekKey}`) || []).filter(workIndex => isFlexible(rows[workIndex]) && isWorking(rows[workIndex]) && safeDaytime(rows[workIndex])).map(workIndex => ({ offIndex, workIndex })));
        // Prefer donors with spare coverage, avoiding irrelevant moves and scans.
        candidates.sort((a, b) => dayMetrics(days.get(rows[b.workIndex].date)).spare - dayMetrics(days.get(rows[a.workIndex].date)).spare || a.offIndex - b.offIndex || a.workIndex - b.workIndex);
        for (const { offIndex, workIndex } of candidates) {
          if (evaluations >= deadline || swaps >= maxSwaps) break;
          const work = rows[workIndex], off = rows[offIndex];
          const oldWorkDay = days.get(work.date), oldOffDay = days.get(off.date);
          const oldWork = dayMetrics(oldWorkDay), oldOff = dayMetrics(oldOffDay);
          const payload = Object.fromEntries(operational.map(field => [field, work[field] ?? '']));
          rows[workIndex] = { ...work, status: 'Folga', shiftStart: '', shiftEnd: '', breakStart: '', breakEnd: '', breakMinutes: 0, extraHours: 0, shift: 'Folga', coverageAdjusted: true, ruleReason: 'Folga reorganizada para atender o mínimo de pessoas' };
          rows[offIndex] = { ...off, ...payload, coverageAdjusted: true, ruleReason: 'Trabalho redistribuído de um dia com mais cobertura' };
          evaluations++;
          const newWorkDay = evaluate(work.date), newOffDay = evaluate(off.date);
          const nextWork = dayMetrics(newWorkDay), nextOff = dayMetrics(newOffDay);
          const oldMissing = oldWork.missing + oldOff.missing, nextMissing = nextWork.missing + nextOff.missing;
          const oldExcess = oldWork.excess + oldOff.excess, nextExcess = nextWork.excess + nextOff.excess;
          const improves = nextMissing < oldMissing || (nextMissing === oldMissing && (nextExcess < oldExcess || (nextExcess === oldExcess && nextWork.severity + nextOff.severity < oldWork.severity + oldOff.severity - 0.001)));
          const keepsCovered = [newWorkDay, newOffDay].every(day => day.rules.every(rule => rule.segments.every(segment => !segment.missing || (days.get(day.date).rules.find(old => old.id === rule.id)?.segments || []).filter(old => time(old.start) < time(segment.end) && time(old.end) > time(segment.start)).every(old => old.missing > 0))));
          const keepsMaximum = [newWorkDay, newOffDay].every(day => day.rules.every(rule => rule.segments.every(segment => !segment.excess || (days.get(day.date).rules.find(old => old.id === rule.id)?.segments || []).filter(old => time(old.start) < time(segment.end) && time(old.end) > time(segment.start)).some(old => old.excess > 0))));
          const valid = improves && keepsCovered && keepsMaximum && !personIssues(work.userId).some(issue => !baselineIssues.get(String(work.userId)).has(issueKey(issue)));
          if (valid) {
            days.set(work.date, newWorkDay); days.set(off.date, newOffDay);
            swaps++; changed = true; applied = true;
            break;
          }
          rows[workIndex] = work; rows[offIndex] = off;
        }
        if (applied) break; // Re-rank deficits after each accepted move.
      }
    }
    if (dates.some(date => dayMetrics(days.get(date)).missing > 0) && (evaluations >= deadline || swaps >= maxSwaps)) limited = true;
  }
  const after = analyzeProposalCoverage(rows, requirements, context);
  if (after.missingMinutes > before.missingMinutes) return { rows: input, before, after: before, swaps: 0, evaluations, limited: true };
  return { rows, before, after, swaps, evaluations, limited };
}

export function planSchedulePublication(rows, history, segments, publicationId) {
  if (!rows.length || !publicationId) throw new Error('Planejamento vazio ou sem identificação.');
  const validDate = value => /^\d{4}-\d{2}-\d{2}$/.test(value || '') && Number.isFinite(Date.parse(`${value}T00:00:00Z`)) && new Date(`${value}T00:00:00Z`).toISOString().slice(0, 10) === value;
  if (rows.some(row => !row.userId || !validDate(row.date))) throw new Error('A simulação contém colaborador ou data inválida. Gere o quadro novamente.');
  const users = new Set(rows.map(row => String(row.userId)));
  const dates = rows.map(row => row.date).sort(), start = dates[0], end = dates.at(-1);
  const rowKeys = new Set(rows.map(keyOf));
  if (rowKeys.size !== rows.length) throw new Error('Há dias repetidos na simulação.');
  for (const userId of users) for (let date = start, count = 0; date <= end; date = shiftDate(date, 1), count++) {
    if (count >= 31 || !rowKeys.has(userId + '|' + date)) throw new Error('A simulação precisa conter todos os dias do período, até 31 dias por vez.');
  }
  const source = history.filter(item => users.has(String(item.userId)) && item.startDate <= end && item.endDate >= start);
  for (const row of rows) {
    if (isProtectedProposalRow(row)) continue;
    if (source.some(item => !isReplaceableSchedule(item) && String(item.userId) === String(row.userId) && inRange(item, row.date))) throw new Error('Uma marcação fixa foi alterada. Gere a simulação novamente.');
  }
  const replaced = source.filter(isReplaceableSchedule);
  if (segments.some(item => !item.id || !users.has(String(item.userId)) || !validDate(item.startDate) || !validDate(item.endDate) || item.startDate > item.endDate || item.startDate < start || item.endDate > end)) throw new Error('Os períodos consolidados da simulação são incompatíveis. Gere o quadro novamente.');
  const cleanData = item => {
    const row = rows.find(candidate => String(candidate.userId) === String(item.userId));
    const sourceData = { ...item, dept: item.dept || row?.dept, userName: item.userName || row?.userName };
    const data = {};
    for (const [field, value] of Object.entries(sourceData)) {
      if (value === undefined) continue;
      if (typeof value === 'number' && !Number.isFinite(value)) throw new Error(`A escala contém um número inválido no campo ${field}. Gere a revisão novamente.`);
      data[field] = value;
    }
    for (const field of ['id', 'userId', 'dept', 'startDate', 'endDate', 'status']) if (!String(data[field] || '').trim()) throw new Error(`A escala contém um registro sem ${field === 'dept' ? 'setor' : field === 'userId' ? 'colaborador' : field}. Corrija o cadastro e gere a revisão novamente.`);
    if (String(data.id).includes('/')) throw new Error('A escala contém uma identificação inválida. Gere a revisão novamente.');
    return data;
  };
  const retained = [];
  replaced.forEach((item, index) => {
    if (item.startDate < start) retained.push({ ...item, id: `schedule-retained-${publicationId}-${index}-left`, endDate: shiftDate(start, -1) });
    if (item.endDate > end) retained.push({ ...item, id: `schedule-retained-${publicationId}-${index}-right`, startDate: shiftDate(end, 1) });
  });
  const published = [...retained, ...segments].map(cleanData);
  const records = [
    ...replaced.map(item => ({ collection: 'schedules', id: item.id, operation: 'delete' })),
    ...published.map(item => ({ collection: 'schedules', id: item.id, data: item })),
  ];
  if (!records.length) return { records: [], replaced, schedules: retained, deletedIds: [] };
  assertSchedulePublicationSize(records, replaced);
  if (new Set(records.map(record => record.id)).size !== records.length) throw new Error('Há identificações repetidas na publicação.');
  return { records, replaced, schedules: published, deletedIds: replaced.map(item => item.id) };
}


