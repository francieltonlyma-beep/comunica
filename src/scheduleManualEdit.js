import { isWorking, shiftDate } from './scheduleDayRules.js';
import { scheduleStatusChange } from './scheduleStatusChange.js';
import { scheduleRowFieldIssues } from './scheduleValidation.js';
import { publishedDayHours } from './publishedScheduleEdit.js';
import { assertSchedulePublicationSize } from './schedulePublicationLimits.js';

const active = (row, date) => (row.startDate || row.date) <= date && (row.endDate || row.date || row.startDate) >= date;

// Resolve each civil day separately: Saturday/Sunday and individual rules may
// have different hours even when the user selects a single continuous period.
export function planManualScheduleEdit({ targets, periods, form, rules, history, publicationId, now, actor, getDepartment }) {
  const edited = [];
  const keys = new Set();
  for (const user of targets) for (const period of periods) {
    for (let date = period.startDate, count = 0; date <= period.endDate; date = shiftDate(date, 1), count++) {
      if (count >= 366 || edited.length >= 366 * targets.length) throw new Error('Salve a escala manual em períodos de até um ano.');
      const key = `${user.id}|${date}`;
      if (keys.has(key)) continue;
      keys.add(key);
      const existing = history.filter(row => String(row.userId) === String(user.id) && active(row, date));
      if (existing.length > 1) throw new Error(`${user.name}: há marcações sobrepostas em ${date.split('-').reverse().join('/')}. Revise este dia antes de alterar.`);
      const source = existing[0];
      const template = source && isWorking(source) && source.shiftStart && source.shiftEnd
        ? { ...source, shiftEnd: source.baseShiftEnd || source.shiftEnd }
        : { userId: user.id, status: 'Folga', workTemplate: source?.workTemplate };
      const hours = scheduleStatusChange({ ...template, userId: user.id, date }, form.status, rules, history, date);
      if (isWorking(hours) && form.shift !== 'Integral') Object.assign(hours, {
        shiftStart: form.customShiftStart || '', shiftEnd: form.customShiftEnd || '',
        breakStart: form.customBreakStart || '', breakEnd: form.customBreakEnd || '', breakMinutes: 0, extraHours: 0,
      });
      const row = { ...hours, userId: user.id, userName: user.name, date };
      const issue = scheduleRowFieldIssues(row)[0];
      if (issue) throw new Error(`${date.split('-').reverse().join('/')} · ${issue.message} Escolha Personalizado para informar os horários.`);
      const totals = publishedDayHours(row);
      edited.push({ id: `schedule-manual-${publicationId}-${edited.length}`, userId: user.id, userName: user.name,
        dept: getDepartment(user), startDate: date, endDate: date, ...hours,
        baseShiftEnd: hours.shiftEnd, shiftEnd: totals.actualEnd,
        shift: isWorking(row) ? `${hours.shiftStart}–${totals.actualEnd}` : form.status,
        breakMinutes: totals.breakMinutes, regularHours: totals.regular, plannedHours: totals.total,
        locked: true, manuallyAdjusted: true, autoGenerated: false,
        recurrence: periods.length > 1 ? { total: periods.length, interval: form.repeatInterval } : null,
        notes: String(form.notes || '').trim(), createdAt: now, updatedAt: now, updatedBy: actor.name,
      });
    }
  }
  // Remove only the selected days from existing ranges, preserving all other
  // dates, including gaps between recurring occurrences and manual markings.
  const replaced = history.filter(row => edited.some(day => String(day.userId) === String(row.userId) && active(row, day.startDate)));
  const retained = [];
  for (const source of replaced) {
    let start = null;
    const end = source.endDate || source.date || source.startDate;
    for (let date = source.startDate || source.date; date <= end; date = shiftDate(date, 1)) {
      if (!keys.has(`${source.userId}|${date}`)) { start ||= date; }
      else if (start) { retained.push({ ...source, id: `schedule-retained-${publicationId}-${retained.length}`, startDate: start, endDate: shiftDate(date, -1) }); start = null; }
    }
    if (start) retained.push({ ...source, id: `schedule-retained-${publicationId}-${retained.length}`, startDate: start, endDate: end });
  }
  const schedules = [...retained, ...edited];
  const records = [...replaced.map(row => ({ collection: 'schedules', id: row.id, operation: 'delete' })),
    ...schedules.map(row => ({ collection: 'schedules', id: row.id, data: row }))];
  assertSchedulePublicationSize(records, replaced);
  return { schedules, edited, records, replaced, deletedIds: replaced.map(row => row.id) };
}
