import test from 'node:test';
import assert from 'node:assert/strict';
import { buildRuleSchedule, holidayWorkTemplate, validateHolidayAssignments, isWorking, shiftDate } from '../src/scheduleDayRules.js';
import { buildCoverageFirstProposal, prepareScheduleProposal } from '../src/scheduleOptimizer.js';

const date = '2026-11-02';
const dates = Array.from({ length: 7 }, (_, index) => shiftDate(date, index));
const users = [{ id: 'a', name: 'Ana' }, { id: 'b', name: 'Beto' }];
const rules = { workDaysPerWeek: 5, restEveryDays: 7, hoursPerWeek: 40, shiftStart: '08:00', shiftEnd: '17:00', breakStart: '12:00', breakEnd: '13:00', allowedWeekdays: [1, 2, 3, 4, 5], holidaysCountAsRest: false, reuseLastSchedule: false };
const build = config => buildRuleSchedule({ dates, users, rules: config, holidays: [date], getDepartment: () => 'op' });

test('feriado desmarcado como descanso permite trabalho normal sem turma cadastrada', () => {
  const rows = build(rules);
  assert.equal(rows.filter(row => row.date === date && isWorking(row)).length, 2);
  assert.ok(rows.every(row => row.status !== 'Feriado'));
  for (const user of users) assert.equal(rows.filter(row => row.userId === user.id && isWorking(row)).length, 5);
});

test('feriado tem decisões individuais com horários próprios mesmo fora dos dias da turma', () => {
  const saturday = shiftDate(date, 5);
  const config = { ...rules, holidaysCountAsRest: true, holidayAssignments: { [saturday]: { a: { status: 'Presencial', shiftStart: '07:00', shiftEnd: '12:00', breakStart: '', breakEnd: '' }, b: { status: 'Folga' } } } };
  const rows = buildRuleSchedule({ dates, users, rules: config, holidays: [saturday], getDepartment: () => 'op' });
  const ana = rows.find(row => row.userId === 'a' && row.date === saturday), beto = rows.find(row => row.userId === 'b' && row.date === saturday);
  assert.equal(ana.status, 'Presencial'); assert.equal(ana.shiftStart, '07:00'); assert.equal(ana.shiftEnd, '12:00');
  assert.equal(ana.pinned, true); assert.equal(ana.holidayConfigured, true);
  assert.equal(beto.status, 'Folga'); assert.equal(beto.pinned, true);
  assert.ok(rows.filter(row => row.date !== saturday).every(row => !row.holidayConfigured));
});

test('escolha individual no feriado preserva ausência e lançamento manual publicados', () => {
  const config = { ...rules, holidayAssignments: { [date]: { a: { status: 'Presencial', shiftStart: '08:00', shiftEnd: '12:00' }, b: { status: 'Presencial', shiftStart: '08:00', shiftEnd: '12:00' } } } };
  const rows = prepareScheduleProposal(build(config), { rules: config, history: [{ id: 'manual', userId: 'a', startDate: date, endDate: date, status: 'Folga' }], absences: [{ userId: 'b', date, reason: 'Férias' }] });
  assert.equal(rows.find(row => row.userId === 'a' && row.date === date).preservedExisting, true);
  assert.equal(rows.find(row => row.userId === 'b' && row.date === date).status, 'Férias');
});

test('feriado automático antigo pode ser corrigido ao regenerar, preservando o registro manual', () => {
  const history = [{ id: 'auto-holiday', userId: 'a', startDate: date, endDate: date, status: 'Feriado', autoGenerated: true }, { id: 'manual-holiday', userId: 'b', startDate: date, endDate: date, status: 'Feriado', locked: true }];
  const rows = prepareScheduleProposal(build(rules), { rules, history });
  assert.equal(rows.find(row => row.userId === 'a' && row.date === date).status, 'Presencial');
  assert.equal(Boolean(rows.find(row => row.userId === 'a' && row.date === date).preservedExisting), false);
  assert.equal(rows.find(row => row.userId === 'b' && row.date === date).status, 'Feriado');
  assert.equal(rows.find(row => row.userId === 'b' && row.date === date).preservedExisting, true);
});

test('modelo individual herda turno, exceção e intervalo vazio sem recuperar intervalo da empresa', () => {
  const config = { ...rules, shifts: [{ id: 'night', shiftStart: '22:00', shiftEnd: '06:00', breakStart: '', breakEnd: '' }], ruleGroups: [{ id: 'g', userIds: ['a'], shiftId: 'night', dayRules: [], policy: {} }], employeeOverrides: { a: { shiftStart: '23:00' } } };
  const template = holidayWorkTemplate('a', date, config);
  assert.equal(template.shiftStart, '23:00'); assert.equal(template.shiftEnd, '06:00'); assert.equal(template.breakStart, '');
  assert.equal(validateHolidayAssignments({ [date]: { a: template } }, [date], ['a']), '');
});

test('valida horários individuais só para as pessoas e feriados deste planejamento', () => {
  for (const entry of [{ status: 'Feriado' }, { status: 'Presencial', shiftStart: '', shiftEnd: '12:00' }, { status: 'Presencial', shiftStart: '08:00', shiftEnd: '12:00', breakStart: '11:00', breakEnd: '13:00' }]) assert.ok(validateHolidayAssignments({ [date]: { a: entry } }, [date], ['a']));
  assert.equal(validateHolidayAssignments({ [date]: { other: { status: 'invalid' } } }, [date], ['a']), '');
  assert.equal(validateHolidayAssignments({ [date]: { a: { status: 'Folga' } } }, [date], ['a']), '');
});

test('otimização pode cobrir feriado normal e mantém escolha individual de folga', () => {
  const holiday = shiftDate(date, 5), manyUsers = Array.from({ length: 4 }, (_, i) => ({ id: String(i), name: String(i) }));
  const config = { ...rules, allowedWeekdays: [0, 1, 2, 3, 4, 5, 6], holidayAssignments: { [holiday]: { 0: { status: 'Folga' } } } };
  const rows = buildRuleSchedule({ dates, users: manyUsers, rules: config, holidays: [holiday], getDepartment: () => 'op' });
  const result = buildCoverageFirstProposal(rows, [{ id: 'need', department: 'op', start: '08:00', end: '12:00', minimum: 2, weekdays: [0, 1, 2, 3, 4, 5, 6] }]);
  assert.equal(result.after.missingMinutes, 0);
  assert.equal(result.rows.find(row => row.userId === '0' && row.date === holiday).status, 'Folga');
});
