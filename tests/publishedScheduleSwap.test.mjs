import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { webcrypto } from 'node:crypto';
import { planPublishedScheduleSwap, publishedScheduleOnDay, publishedSwapCandidates, publishedSwapCoverage, publishedSwapIssues } from '../src/publishedScheduleSwap.js';
import { scheduleSignature } from '../src/scheduleOptimizer.js';

const work = { id: 'ana-period', userId: 'ana', userName: 'Ana', dept: 'loja', startDate: '2026-11-01', endDate: '2026-11-30', status: 'Presencial', shiftStart: '08:00', baseShiftEnd: '17:00', shiftEnd: '17:00', breakStart: '12:00', breakEnd: '13:00', breakMinutes: 60, extraHours: 0, autoGenerated: true };
const off = { id: 'bia-period', userId: 'bia', userName: 'Bia', dept: 'loja', startDate: '2026-11-01', endDate: '2026-11-30', status: 'Folga', shiftStart: '', shiftEnd: '', autoGenerated: true };
const sourceDate = '2026-11-10', targetDate = '2026-11-12';
const history = [work, off];
const context = { history, absences: [], rules: { restEveryDays: 7 }, publicationId: 'swap-id', actor: { id: 'admin', name: 'Gestora' }, now: 10 };

test('localiza uma única escala editável e oferece somente outras pessoas publicadas', () => {
  assert.equal(publishedScheduleOnDay(history, 'ana', sourceDate), work);
  assert.equal(publishedScheduleOnDay([...history, { ...work, id: 'duplicada' }], 'ana', sourceDate), null);
  assert.deepEqual(publishedSwapCandidates(work, sourceDate, history, [{ id: 'ana', name: 'Ana' }, { id: 'sem', name: 'Sem escala' }, { id: 'bia', name: 'Bia' }]).map(person => person.id), ['bia']);
});

test('troca folga e jornada em dias diferentes preservando identidade e restante dos períodos', () => {
  const plan = planPublishedScheduleSwap(work, sourceDate, off, targetDate, { ...context, reason: 'Troca combinada' });
  assert.equal(plan.replaced.length, 2);
  assert.equal(plan.records.filter(record => record.operation === 'delete').length, 2);
  assert.equal(plan.schedules.length, 6);
  const anaDay = plan.schedules.find(row => row.userId === 'ana' && row.startDate === sourceDate && row.endDate === sourceDate);
  const biaDay = plan.schedules.find(row => row.userId === 'bia' && row.startDate === targetDate && row.endDate === targetDate);
  assert.equal(anaDay.status, 'Folga'); assert.equal(anaDay.userName, 'Ana'); assert.equal(anaDay.adjustmentReason, 'Troca combinada');
  assert.equal(biaDay.status, 'Presencial'); assert.equal(biaDay.shiftStart, '08:00'); assert.equal(biaDay.baseShiftEnd, '17:00'); assert.equal(biaDay.userName, 'Bia');
  for (const row of [anaDay, biaDay]) { assert.equal(row.locked, true); assert.equal(row.manuallyAdjusted, true); assert.equal(row.updatedBy, 'Gestora'); }
  assert.ok(plan.schedules.some(row => row.userId === 'ana' && row.endDate === '2026-11-09'));
  assert.ok(plan.schedules.some(row => row.userId === 'bia' && row.startDate === '2026-11-13'));
  assert.equal(new Set(plan.records.map(record => record.id)).size, plan.records.length);
});

test('bloqueia mesma pessoa, sobreposição e ausência integral para quem receberia trabalho', () => {
  assert.ok(publishedSwapIssues(work, sourceDate, work, targetDate, context).length);
  assert.ok(publishedSwapIssues(work, sourceDate, off, targetDate, { ...context, history: [...history, { ...off, id: 'bia-duplicada' }] }).length);
  assert.match(publishedSwapIssues(work, sourceDate, off, targetDate, { ...context, absences: [{ userId: 'bia', date: targetDate }] }).join(' '), /ausência de dia inteiro/);
});

test('prévia de cobertura considera os dois dias e jornadas noturnas', () => {
  const night = { ...work, shiftStart: '22:00', baseShiftEnd: '06:00', shiftEnd: '06:00', breakStart: '', breakEnd: '', breakMinutes: 0 };
  const ctx = { ...context, history: [night, off], employees: [{ id: 'ana', depts: ['loja'] }, { id: 'bia', depts: ['loja'] }], getDepartments: person => person.depts };
  const requirements = [{ id: 'need', department: 'loja', weekdays: [3, 5], start: '00:00', end: '06:00', minimum: 1 }];
  const days = publishedSwapCoverage(night, sourceDate, off, targetDate, requirements, ctx);
  assert.deepEqual(days.map(day => day.date), ['2026-11-10', '2026-11-11', '2026-11-12', '2026-11-13']);
  assert.equal(days[1].before.status, 'sufficient'); assert.equal(days[1].after.status, 'shortage');
  assert.equal(days[3].before.rules[0].segments[0].available, 1); assert.equal(days[3].after.rules[0].segments[0].available, 1);
});

const app = readFileSync(new URL('../src/App.jsx', import.meta.url), 'utf8');
const extract = (name, next, ctx) => vm.runInNewContext('(' + app.split('const ' + name + ' = ')[1].split('const ' + next + ' = ')[0].trim().replace(/;$/, '') + ')', ctx);

test('salvamento real confirma os dois registros em uma transação protegida', async () => {
  for (const ok of [false, true]) {
    const swap = { source: work, date: sourceDate, companyId: 'company', history, absences: [], rules: context.rules };
    const ctx = { currentUser: { id: 'admin', name: 'Gestora', isAdmin: true }, isManager: true, effectiveAccessProfile: {}, publishedScheduleSwap: swap,
      isSavingPublishedSchedule: false, activeCompany: { id: 'company' }, workSchedules: history, absences: [], automaticScheduleRules: context.rules,
      schedulePlanningDataReady: () => true, scheduleSignature, planPublishedScheduleSwap, crypto: webcrypto, notifications: [], writes: [], setIsSavingPublishedSchedule() {},
    };
    ctx.triggerNotification = message => ctx.notifications.push(message);
    ctx.saveRelatedRecords = async (...args) => { ctx.writes.push(args); return ok; };
    ctx.setPublishedScheduleSwap = value => { ctx.closed = value; };
    const result = await extract('savePublishedScheduleSwap', 'openPublishedScheduleEdit', ctx)({ target: off, targetDate, reason: '' });
    assert.equal(result, ok); assert.equal(ctx.writes.length, 1); assert.equal(ctx.writes[0][2].replaced.length, 2); assert.equal(ctx.closed, ok ? null : undefined);
  }
});
