import test from 'node:test';
import assert from 'node:assert/strict';
import { planSchedulePublication } from '../src/scheduleOptimizer.js';
import { assertSchedulePublicationSize } from '../src/schedulePublicationLimits.js';
import { shiftDate } from '../src/scheduleDayRules.js';

test('mês com 30 colaboradores e mais de 1800 operações preserva dias fixos e datas externas', () => {
  const rows = [], history = [], segments = [];
  for (let employee = 0; employee < 30; employee++) {
    const userId = `employee-${employee}`;
    history.push({ id: `old-month-${employee}`, userId, dept: 'op', startDate: '2026-09-01', endDate: '2026-11-30', status: 'Folga', autoGenerated: true });
    for (let day = 0; day < 31; day++) {
      const date = shiftDate('2026-10-01', day);
      const preserved = employee === 0 && day === 10;
      rows.push({ key: `${userId}-${date}`, userId, date, dept: 'op', preservedExisting: preserved, status: 'Folga' });
      if (!preserved) segments.push({ id: `new-${employee}-${day}`, userId, dept: 'op', startDate: date, endDate: date, status: 'Folga', autoGenerated: true });
      history.push({ id: `old-day-${employee}-${day}`, userId, dept: 'op', startDate: date, endDate: date, status: 'Folga', autoGenerated: true });
    }
  }
  history.push({ id: 'fixed', userId: 'employee-0', dept: 'op', startDate: '2026-10-11', endDate: '2026-10-11', status: 'Folga', locked: true });
  const plan = planSchedulePublication(rows, history, segments, 'publication-large');
  assert.ok(plan.records.length > 1800);
  assert.equal(plan.records.filter(record => record.operation === 'delete').length, 960);
  assert.equal(plan.schedules.filter(record => record.endDate === '2026-09-30').length, 30);
  assert.equal(plan.schedules.filter(record => record.startDate === '2026-11-01').length, 30);
  assert.ok(!plan.records.some(record => record.id === 'fixed'));
  assert.equal(new Set(plan.records.map(record => record.id)).size, plan.records.length);
});

test('proteção mede bytes UTF-8 e considera os registros antigos substituídos', () => {
  const ascii = [{ id: 'a', data: { notes: 'a'.repeat(1000) } }];
  const unicode = [{ id: 'a', data: { notes: '😀'.repeat(1000) } }];
  assert.ok(assertSchedulePublicationSize(unicode) > assertSchedulePublicationSize(ascii));
  assert.throws(() => assertSchedulePublicationSize(ascii, [{ notes: 'x'.repeat(7 * 1024 * 1024) }]), { code: 'schedule-publication-size' });
});
