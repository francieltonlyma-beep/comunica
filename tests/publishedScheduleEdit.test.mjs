import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { webcrypto } from 'node:crypto';
import { publishedScheduleDraft, publishedEditIssues, planPublishedDayEdit, publishedEditCoverage, publishedDayHours, canEditPublishedSchedule, coverageMissingMinutes } from '../src/publishedScheduleEdit.js';
import { scheduleSignature } from '../src/scheduleOptimizer.js';
const source = { id: 'source', userId: 'u', userName: 'Ana', dept: 'op', startDate: '2026-11-02', endDate: '2026-11-06', status: 'Presencial', shiftStart: '08:00', baseShiftEnd: '17:00', shiftEnd: '18:00', breakStart: '12:00', breakEnd: '13:00', breakMinutes: 60, extraHours: 1, autoGenerated: true, notes: 'Manter', updatedAt: 1, updatedBy: 'Anterior' };
const date = '2026-11-04';
const context = { history: [source], absences: [], rules: { restEveryDays: 7 }, publicationId: 'edit-id', actor: { id: 'admin', name: 'Gestora' }, now: 2 };

test('ajuste central divide período, preserva extremos e registra autor apenas no dia editado', () => {
  const draft = { ...publishedScheduleDraft(source), status: 'Folga', reason: 'Troca solicitada' };
  const plan = planPublishedDayEdit(source, draft, date, context);
  assert.equal(plan.records.length, 4); assert.equal(plan.records[0].operation, 'delete');
  const [left, right, edited] = plan.schedules;
  assert.equal(left.endDate, '2026-11-03'); assert.equal(right.startDate, '2026-11-05');
  for (const row of [left, right]) { assert.equal(row.status, source.status); assert.equal(row.updatedBy, 'Anterior'); assert.equal(row.extraHours, 1); assert.equal(row.notes, 'Manter'); }
  assert.equal(edited.startDate, date); assert.equal(edited.endDate, date); assert.equal(edited.status, 'Folga');
  assert.equal(edited.shiftStart, ''); assert.equal(edited.extraHours, 0); assert.equal(edited.plannedHours, 0);
  assert.equal(edited.locked, true); assert.equal(edited.manuallyAdjusted, true); assert.equal(edited.autoGenerated, false);
  assert.equal(edited.updatedBy, 'Gestora'); assert.equal(edited.updatedById, 'admin'); assert.equal(edited.adjustmentReason, draft.reason);
  assert.equal(new Set(plan.schedules.map(row => row.id)).size, 3);
});

test('extremos produzem só um fragmento e escala de um dia mantém a identificação', () => {
  for (const selected of [source.startDate, source.endDate]) assert.equal(planPublishedDayEdit(source, publishedScheduleDraft(source), selected, context).schedules.length, 2);
  const single = { ...source, startDate: date, endDate: date };
  const plan = planPublishedDayEdit(single, publishedScheduleDraft(single), date, { ...context, history: [single] });
  assert.equal(plan.records.length, 1); assert.equal(plan.records[0].operation, 'update'); assert.equal(plan.records[0].id, source.id);
});

test('hora extra não é contada duas vezes e registro antigo sem base é tratado explicitamente', () => {
  const draft = publishedScheduleDraft(source);
  assert.equal(draft.shiftEnd, '17:00'); assert.equal(publishedDayHours(draft).actualEnd, '18:00'); assert.equal(publishedDayHours(draft).total, 9);
  const legacy = { ...source }; delete legacy.baseShiftEnd;
  assert.equal(publishedScheduleDraft(legacy).shiftEnd, '18:00'); assert.equal(publishedScheduleDraft(legacy).extraHours, 0);
});

test('recusa jornadas inválidas, ausências integrais, sobreposição e sétimo dia consecutivo', () => {
  const draft = publishedScheduleDraft(source);
  for (const patch of [{ shiftStart: '' }, { shiftEnd: '08:00' }, { breakEnd: '' }, { breakStart: '06:00', breakEnd: '07:00' }, { extraHours: 13 }, { extraHours: NaN }]) assert.ok(publishedEditIssues(source, { ...draft, ...patch }, date, context).length);
  assert.ok(publishedEditIssues(source, draft, '2026-02-31', context).length);
  assert.ok(publishedEditIssues(source, draft, '2026-12-04', context).length);
  assert.ok(publishedEditIssues(source, draft, date, { ...context, absences: [{ userId: 'u', date }] }).length);
  assert.ok(publishedEditIssues(source, draft, date, { ...context, history: [source, { ...source, id: 'duplicate' }] }).length);
  const week = { ...source, startDate: '2026-10-29', endDate: date };
  assert.match(publishedEditIssues(week, draft, date, { ...context, history: [week] }).join(' '), /7 dias consecutivos/);
  assert.equal(canEditPublishedSchedule({ ...source, status: 'Férias' }), false);
});

test('cobertura usa toda a equipe e compara também o dia seguinte em turno noturno', () => {
  const night = { ...source, shiftStart: '22:00', baseShiftEnd: '06:00', shiftEnd: '06:00', breakStart: '', breakEnd: '', breakMinutes: 0, extraHours: 0 };
  const ctx = { ...context, history: [night], employees: [{ id: 'u', depts: ['op'] }], getDepartments: user => user.depts };
  const req = [{ id: 'need', department: 'op', weekdays: [4], start: '00:00', end: '06:00', minimum: 1 }];
  const comparison = publishedEditCoverage(night, { ...publishedScheduleDraft(night), status: 'Folga' }, date, req, ctx);
  assert.equal(comparison[1].date, '2026-11-05');
  assert.equal(coverageMissingMinutes(comparison[1].before), 0);
  assert.equal(coverageMissingMinutes(comparison[1].after), 360);
});

const app = readFileSync(new URL('../src/App.jsx', import.meta.url), 'utf8');
const extract = (name, next, ctx) => vm.runInNewContext('(' + app.split('const ' + name + ' = ')[1].split('const ' + next + ' = ')[0].trim().replace(/;$/, '') + ')', ctx);
function savingContext(ok = true) {
  const ctx = { currentUser: { id: 'admin', name: 'Gestora', isAdmin: true }, isManager: true, effectiveAccessProfile: {},
    publishedScheduleEdit: { source, date, companyId: 'company', history: [source], absences: [], rules: context.rules }, isSavingPublishedSchedule: false,
    activeCompany: { id: 'company' }, workSchedules: [source], absences: [], automaticScheduleRules: context.rules,
    schedulePlanningDataReady: () => true, scheduleSignature, planPublishedDayEdit, canEditPublishedSchedule, crypto: webcrypto,
    notifications: [], writes: [], setIsSavingPublishedSchedule() {},
  };
  ctx.triggerNotification = message => ctx.notifications.push(message);
  ctx.saveRelatedRecords = async (...args) => { ctx.writes.push(args); return ok; };
  ctx.setWorkSchedules = update => { ctx.updated = update(ctx.workSchedules); };
  ctx.setPublishedScheduleEdit = value => { ctx.closed = value; };
  return ctx;
}

test('salvamento real usa operação conjunta e só muda a tela após confirmação', async () => {
  for (const ok of [false, true]) {
    const ctx = savingContext(ok);
    const result = await extract('savePublishedScheduleEdit', 'handleDeleteSchedule', ctx)({ ...publishedScheduleDraft(source), status: 'Folga' });
    assert.equal(result, ok); assert.equal(ctx.writes.length, 1);
    assert.equal(ctx.writes[0][0].length, 4); assert.equal(ctx.writes[0][2].companyId, 'company');
    assert.equal(ctx.updated, undefined); assert.equal(ctx.closed, ok ? null : undefined);
  }
});

test('mudança de empresa, versão desatualizada ou perda de permissão impedem escrita', async () => {
  for (const patch of [{ activeCompany: { id: 'other' } }, { workSchedules: [] }, { absences: [{ userId: 'u', date }] }, { currentUser: { id: 'u', isAdmin: false }, effectiveAccessProfile: { canEdit: false } }, { isManager: false, currentUser: { id: 'u', isAdmin: false } }, { automaticScheduleRules: { restEveryDays: 6 } }]) {
    const ctx = { ...savingContext(), ...patch };
    assert.equal(await extract('savePublishedScheduleEdit', 'handleDeleteSchedule', ctx)(publishedScheduleDraft(source)), false);
    assert.equal(ctx.writes.length, 0);
  }
});
