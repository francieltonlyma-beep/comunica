import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { webcrypto } from 'node:crypto';
import { isProtectedProposalRow, planSchedulePublication, prepareScheduleProposal, scheduleSignature } from '../src/scheduleOptimizer.js';
import { shiftDate, scheduleRuleIssues } from '../src/scheduleDayRules.js';

const app = readFileSync(new URL('../src/App.jsx', import.meta.url), 'utf8');
const extract = (name, next, context) => vm.runInNewContext('(' + app.split('const ' + name + ' = ')[1].split('const ' + next + ' = ')[0].trim().replace(/;$/, '') + ')', context);
const history = [
  { id: 'auto', userId: 'u', startDate: '2026-11-01', endDate: '2026-11-30', status: 'Folga', autoGenerated: true },
  { id: 'manual', userId: 'u', startDate: '2026-11-03', endDate: '2026-11-03', status: 'Folga', locked: true },
];
function publicationContext(saved = true) {
  const writes = [], notifications = [], modal = [];
  const rows = ['2026-11-02', '2026-11-03', '2026-11-04'].map(date => ({ key: 'u-' + date, userId: 'u', userName: 'Pessoa', dept: 'op', date, weekKey: '2026-11-02', status: 'Presencial', shiftStart: '08:00', shiftEnd: '17:00', breakStart: '12:00', breakEnd: '13:00', breakMinutes: 60, extraHours: 0 }));
  const context = {
    crypto: webcrypto, isSavingScheduleProposal: false, isManager: true, currentUser: { isAdmin: true, name: 'Admin' },
    effectiveAccessProfile: {}, schedulePlanningDataReady: () => true,
    automaticScheduleInput: 'same', automaticScheduleProposalInput: 'same',
    automaticScheduleProposal: prepareScheduleProposal(rows, { history }), workSchedules: history, activeCompany: { id: 'company' },
    isProtectedProposalRow, scheduleRuleIssues, planSchedulePublication,
    civilDateShift: (date, { days = 0 }) => shiftDate(date, days),
    bulkSchedule: { notes: '' }, setAutomaticSchedulePreviewDate() {}, setIsSavingScheduleProposal() {},
    saveRelatedRecords: async (...args) => { writes.push(args); return saved; },
    setWorkSchedules: update => { context.updated = update(history); },
    setAutomaticScheduleProposal: value => { context.draft = value; },
    setAutomaticScheduleOptimization() {}, setShowBulkScheduleModal: value => modal.push(value),
    triggerNotification: message => notifications.push(message),
  };
  for (const [name, next] of [['scheduleTimeToMinutes', 'scheduleMinutesToTime'], ['scheduleMinutesToTime', 'scheduleDurationToText'], ['scheduleIntervalMinutes', 'scheduleTimeWithinShift'], ['scheduleTimeWithinShift', 'automaticScheduleRowHours'], ['automaticScheduleRowHours', 'updateAutomaticScheduleRow']]) context[name] = extract(name, next, context);
  return { context, writes, notifications, modal };
}

test('publicação real envia exclusão e substituição juntas, com cópias externas ao período', async () => {
  const state = publicationContext();
  await extract('saveAutomaticScheduleProposal', 'saveBulkSchedule', state.context)();
  const [records, , guard] = state.writes[0];
  assert.equal(records.filter(item => item.operation === 'delete').length, 1);
  assert.equal(records.filter(item => item.operation === 'delete')[0].id, 'auto');
  assert.ok(!records.some(item => item.id === 'manual'));
  assert.ok(state.context.updated.some(item => item.id === 'manual'));
  assert.ok(state.context.updated.some(item => item.endDate === '2026-11-01'));
  assert.ok(state.context.updated.some(item => item.startDate === '2026-11-05'));
  assert.equal(guard.companyId, 'company');
  assert.deepEqual(state.modal, [false]);
});

test('falha de publicação preserva prévia e lançamentos existentes', async () => {
  const state = publicationContext(false);
  await extract('saveAutomaticScheduleProposal', 'saveBulkSchedule', state.context)();
  assert.equal(state.writes.length, 1);
  assert.equal(state.context.updated, undefined);
  assert.equal(state.context.draft, undefined);
  assert.equal(state.modal.length, 0);
});

test('simulação desatualizada ou perfil de consulta não escreve', async () => {
  for (const readonly of [false, true]) {
    const state = publicationContext();
    if (readonly) { state.context.currentUser.isAdmin = false; state.context.effectiveAccessProfile.canManageCalendar = false; }
    else state.context.automaticScheduleInput = 'changed';
    await extract('saveAutomaticScheduleProposal', 'saveBulkSchedule', state.context)();
    assert.equal(state.writes.length, 0);
    assert.ok(state.notifications.length > 0);
  }
});

function transactionContext({ changedBefore = false, changedDuring = false, fail = false } = {}) {
  const source = [history[0]], committed = [], notifications = [];
  const snapshot = item => ({ id: item.id, exists: () => true, data: () => ({ ...item }) });
  const context = {
    isFirebaseAvailable: true, dbUser: { uid: 'admin' }, activeCompany: { id: 'company' }, db: {},
    getTenantCollection: () => 'schedules', doc: (collection, id) => collection + '/' + id, scheduleSignature,
    getDocsFromServer: async () => ({ docs: (changedBefore ? [{ ...source[0], locked: true }] : source).map(snapshot) }),
    runTransaction: async (db, callback) => {
      const pending = [];
      await callback({
        get: async () => snapshot(changedDuring ? { ...source[0], locked: true } : source[0]),
        delete: ref => pending.push(['delete', ref]), set: (ref, data) => pending.push(['set', ref, data]),
      });
      if (fail) throw Error('offline');
      committed.push(...pending);
    },
    triggerNotification: message => notifications.push(message),
    console: { error() {} },
  };
  return { context, source, committed, notifications };
}

test('transação aborta quando outro gestor fixa um lançamento durante a revisão', async () => {
  for (const options of [{ changedBefore: true }, { changedDuring: true }, { fail: true }]) {
    const state = transactionContext(options);
    const save = extract('saveRelatedRecords', 'updateDocField', state.context);
    const ok = await save([{ collection: 'schedules', id: 'auto', operation: 'delete' }, { collection: 'schedules', id: 'new', data: { status: 'Folga' } }], 'Falha', { companyId: 'company', history: state.source, replaced: state.source });
    assert.equal(ok, false);
    assert.equal(state.committed.length, 0);
  }
});

test('transação confirma exclusão e novas escalas sem gravações parciais', async () => {
  const state = transactionContext();
  const ok = await extract('saveRelatedRecords', 'updateDocField', state.context)(
    [{ collection: 'schedules', id: 'auto', operation: 'delete' }, { collection: 'schedules', id: 'new', data: { status: 'Folga' } }],
    'Falha', { companyId: 'company', history: state.source, replaced: state.source },
  );
  assert.equal(ok, true);
  assert.deepEqual(state.committed.map(item => item[0]), ['delete', 'set']);
});
