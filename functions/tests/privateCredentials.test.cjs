test('support requires private authorization and private PIN, independent of public flags', async () => {
  const scope={appId:'comunica-salvador',companyId:'support-fixture',userId:SUPPORT_UID};
  const access=db.doc(`_platformSupport/${SUPPORT_UID}`);
  await access.delete();
  await db.doc(`artifacts/${scope.appId}/public/data/companies/${scope.companyId}/users/${SUPPORT_UID}`).set({isDeveloper:true,pin:'5273'});
  assert.equal(await verifyPlatformSupport(db,scope.appId,'5273'),null);
  await access.set({enabled:true,appId:scope.appId,companyId:scope.companyId});
  assert.equal(await verifyPlatformSupport(db,scope.appId,'5273'),null);
  await privateCredentials(db).create(scope,'6342');
  assert.equal(await verifyPlatformSupport(db,scope.appId,'5273'),null);
  assert.deepEqual(await verifyPlatformSupport(db,scope.appId,'6342'),scope);
  assert.equal(await verifyPlatformSupport(db,'other-app','6342'),null);
  await access.update({enabled:false});
  assert.equal(await verifyPlatformSupport(db,scope.appId,'6342'),null);
});

test('employee registration is atomic, private and restricted to current company admins', async () => {
  const companyId = 'registration-'+Date.now();
  const company = db.doc(`artifacts/test/public/data/companies/${companyId}`);
  await company.collection('users').doc('admin').set({isAdmin:true});
  await company.collection('users').doc('member').set({isAdmin:false});
  const profile={name:'Fixture',depts:['production'],isDeveloper:true,pin:'do-not-copy',pushTokens:['untrusted']};
  const create=(actor,id,tenant=companyId)=>registerEmployee(db,'test',tenant,actor,id,profile,'5273');
  await assert.rejects(()=>create('member','denied'));
  await assert.rejects(()=>create('admin','denied','other-company'));
  assert.equal((await company.collection('users').doc('denied').get()).exists,false);
  const result=await create('admin','employee');
  assert.equal(result.user.pin,undefined);
  assert.equal(result.user.isDeveloper,false);
  assert.equal(result.user.pushTokens,undefined);
  assert.equal(result.presence.status,'Presencial');
  assert.equal((await company.collection('presence').doc('pres-employee').get()).exists,true);
  const service=privateCredentials(db);
  assert.equal(await service.verify({appId:'test',companyId,userId:'employee'},'5273'),'ok');
  await assert.rejects(()=>create('admin','employee'));
  // A conflicting presence document must roll back both the profile and secret.
  await company.collection('presence').doc('pres-conflict').set({fixture:true});
  await assert.rejects(()=>create('admin','conflict'));
  assert.equal((await company.collection('users').doc('conflict').get()).exists,false);
  assert.equal(await service.verify({appId:'test',companyId,userId:'conflict'},'5273'),'invalid');
  await assert.rejects(()=>create('admin','platform-support-francielton'));
  await company.collection('users').doc('admin').update({isAdmin:false});
  await assert.rejects(()=>create('admin','revoked'));
});
