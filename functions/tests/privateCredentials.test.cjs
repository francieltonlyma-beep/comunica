test('admin reset checks current membership, tenant and protected support atomically', async () => {
  const service = privateCredentials(db);
  const scope = {appId:'test',companyId:'reset-'+Date.now(),userId:'employee'};
  const users = db.collection(`artifacts/${scope.appId}/public/data/companies/${scope.companyId}/users`);
  await users.doc('admin').set({isAdmin:true});
  await users.doc('member').set({isAdmin:false});
  await users.doc(scope.userId).set({name:'Fixture',pin:'5273'});
  await service.migrateLegacy(scope);
  assert.equal(await service.resetByCompanyAdmin(scope,'other','admin','6342'),false);
  assert.equal(await service.resetByCompanyAdmin(scope,scope.companyId,'member','6342'),false);
  assert.equal(await service.resetByCompanyAdmin(scope,scope.companyId,'absent','6342'),false);
  assert.equal(await service.resetByCompanyAdmin({...scope,userId:'missing'},scope.companyId,'admin','6342'),false);
  await users.doc('platform-support-francielton').set({isDeveloper:false});
  assert.equal(await service.resetByCompanyAdmin({...scope,userId:'platform-support-francielton'},scope.companyId,'admin','6342'),false);
  await users.doc('developer').set({isDeveloper:true});
  assert.equal(await service.resetByCompanyAdmin({...scope,userId:'developer'},scope.companyId,'admin','6342'),false);
  assert.equal(await service.verify(scope,'5273'),'ok');
  assert.equal(await service.resetByCompanyAdmin(scope,scope.companyId,'admin','6342'),true);
  assert.equal(await service.verify(scope,'5273'),'invalid');
  assert.equal(await service.verify(scope,'6342'),'ok');
  assert.equal((await users.doc(scope.userId).get()).data().pin,undefined);
  const secret=(await db.collection('_privateCredentials').doc(credentialKey(scope)).get()).data();
  assert.equal(secret.resetBy,'admin');
  assert.ok(secret.resetAt);
  assert.equal(secret.revision,2);
  await users.doc('admin').update({isAdmin:false});
  assert.equal(await service.resetByCompanyAdmin(scope,scope.companyId,'admin','7777'),false);
  assert.equal(await service.verify(scope,'6342'),'ok');
});
test('hash salted, rejects malformed digests and invalid formats', () => {
  const first = hashPin('5273');
  assert.notDeepEqual(first, hashPin('5273'));
  assert.equal(matchesPin('5273', first), true);
  assert.equal(matchesPin('5274', first), false);
  assert.equal(matchesPin('5273', {...first, digest: 'broken'}), false);
  assert.throws(() => hashPin('abcd'));
});
test('persistent credentials: isolation, lockout, changes and no plaintext', async () => {
  let clock = 1800000000000;
  const service = privateCredentials(db, () => clock);
  const scope = {appId:'test', companyId:'a', userId:'fixture-'+Date.now()};
  await service.create(scope, '5273');
  await assert.rejects(() => service.create(scope, '9999'));
  assert.equal(await service.verify({...scope, companyId:'b'}, '5273'), 'invalid');
  assert.equal(await service.verify(scope, '5273'), 'ok');
  await Promise.all(Array.from({length:5}, () => service.verify(scope,'0000')));
  assert.equal(await service.verify(scope, '5273'), 'locked');
  clock += 30*1000-1;
  assert.equal(await service.verify(scope, '5273'), 'locked');
  clock += 2;
  assert.equal(await service.verify(scope, '5273'), 'ok');
  const legacyLock = db.collection('_privateCredentials').doc(credentialKey(scope));
  await legacyLock.update({failures: 5, lockedUntil: clock + 15*60*1000,
    lockDurationMs: FieldValue.delete()});
  assert.equal(await service.verify(scope, '5273'), 'ok');
  assert.equal(await service.change(scope, '0000', '634215'), false);
  assert.equal(await service.change(scope, '5273', '634215'), true);
  assert.equal(await service.verify(scope, '5273'), 'invalid');
  assert.equal(await service.verify(scope, '634215'), 'ok');
  const data = (await db.collection('_privateCredentials').doc(credentialKey(scope)).get()).data();
  assert.equal(data.pin, undefined);
  assert.equal(data.revision, 2);
  assert.equal(JSON.stringify(data).includes('634215'), false);
});
test('legacy migration is atomic, preserves PIN, and cannot overwrite a changed secret', async () => {
  const service = privateCredentials(db);
  const scope = {appId:'test', companyId:'legacy', userId:'fixture-'+Date.now()};
  const user = db.doc(`artifacts/${scope.appId}/public/data/companies/${scope.companyId}/users/${scope.userId}`);
  await user.set({name:'Fixture',pin:'5273',isAdmin:false});
  await Promise.all([service.migrateLegacy(scope),service.migrateLegacy(scope)]);
  assert.equal((await user.get()).data().pin, undefined);
  assert.equal((await user.get()).data().name,'Fixture');
  assert.equal(await service.verify(scope,'5273'),'ok');
  assert.equal(await service.change(scope,'5273','6342'),true);
  await user.update({pin:'5273'}); // An obsolete client must not replace the new secret.
  assert.equal(await service.migrateLegacy(scope),true);
  assert.equal(await service.verify(scope,'5273'),'invalid');
  assert.equal(await service.verify(scope,'6342'),'ok');
  assert.equal((await user.get()).data().pin,undefined);
  await user.delete();
  assert.equal(await service.migrateLegacy(scope),false);
  await user.set({name:'No credential'});
  const absent={...scope,userId:scope.userId+'-absent'};
  await db.doc(`artifacts/${absent.appId}/public/data/companies/${absent.companyId}/users/${absent.userId}`).set({name:'No credential'});
  assert.equal(await service.migrateLegacy(absent),false);
  assert.equal(await service.verify(absent,'1234'),'invalid');
});
