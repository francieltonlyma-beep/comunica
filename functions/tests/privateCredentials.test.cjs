const {test, after} = require('node:test');
const assert = require('node:assert/strict');
const {initializeApp, deleteApp} = require('firebase-admin/app');
const {getFirestore, FieldValue} = require('firebase-admin/firestore');
const {hashPin, matchesPin, credentialKey, privateCredentials} = require('../lib/privateCredentials');
if (process.env.FIRESTORE_EMULATOR_HOST !== '127.0.0.1:8080') throw new Error('Local emulator required');
const app = initializeApp({projectId: 'demo-comunica-credentials'});
