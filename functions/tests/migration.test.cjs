const {test,after}=require('node:test');
const assert=require('node:assert/strict');
const {execFileSync}=require('node:child_process');
const path=require('node:path');
const {initializeApp,deleteApp}=require('firebase-admin/app');
const {getFirestore}=require('firebase-admin/firestore');
if(process.env.FIRESTORE_EMULATOR_HOST!=='127.0.0.1:8080')throw new Error('Local emulator required');
const app=initializeApp({projectId:'demo-comunica-migration'});
const db=getFirestore(app);
after(async()=>{await db.terminate();await deleteApp(app);});
const run=mode=>JSON.parse(execFileSync(process.execPath,[path.resolve(__dirname,'../scripts/migrate-private-credentials.cjs'),'--emulator',mode],{encoding:'utf8',stdio:['pipe','pipe','pipe'],windowsHide:true}));
test('migration prepares without removing PINs, is idempotent and fails atomically on changed data',async()=>{
 const cleared=await fetch('http://127.0.0.1:8080/emulator/v1/projects/demo-comunica-migration/databases/(default)/documents',{method:'DELETE'});
 assert.equal(cleared.ok,true);
 const company=db.doc('artifacts/comunica-salvador/public/data/companies/fixture');
 await company.set({code:'FIXTURE'});
 await company.collection('users').doc('platform-support-francielton').set({pin:'5273',isDeveloper:true});
 const user=company.collection('users').doc('worker');
 await user.set({pin:'6342',name:'Fixture'});
 assert.equal(run('--prepare').writes,5);
 assert.equal((await user.get()).data().pin,'6342');
 assert.equal(run('--prepare').writes,0);
 await user.update({pin:'1111'});
 assert.throws(()=>run('--finalize'));
 assert.equal((await company.collection('users').doc('platform-support-francielton').get()).data().pin,'5273');
 await user.update({pin:'6342'});
 assert.equal(run('--finalize').writes,4);
 assert.equal((await user.get()).data().pin,undefined);
 assert.equal((await user.get()).data().name,'Fixture');
 assert.equal(run('--finalize').writes,0);
});
